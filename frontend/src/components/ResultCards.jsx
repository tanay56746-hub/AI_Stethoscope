import React from 'react';

/**
 * ResultCards Component
 * Displays the 3 multi-task classification heads:
 * 1. Heart Sound Analysis (Normal / Abnormal)
 * 2. Lung Acoustic Analysis (Normal / Crackle / Wheeze / Crackle+Wheeze)
 * 3. Lung Disease Classification (Normal / Asthma / Other)
 */
export default function ResultCards({ results }) {
  if (!results) return null;

  const { heart, lung_acoustic, lung_disease } = results;

  const getBadgeClass = (pred) => {
    const p = (pred || '').toLowerCase();
    if (p === 'normal') return 'badge-normal';
    if (p === 'abnormal') return 'badge-abnormal';
    if (p.includes('wheeze')) return 'badge-wheeze';
    if (p.includes('crackle')) return 'badge-crackle';
    if (p === 'asthma') return 'badge-asthma';
    return 'badge-other';
  };

  return (
    <div>
      <div className="results-cards-grid">
        {/* CARD 1 — HEART SOUND */}
        <div className="result-card highlighted">
          <div className="result-header">
            <div className="result-task-title">Heart Sound Analysis</div>
            <span className={`result-prediction-badge ${getBadgeClass(heart?.prediction)}`}>
              {heart?.prediction?.toUpperCase() || '—'}
            </span>
          </div>

          <div className="prob-list">
            {heart &&
              Object.entries(heart.probabilities).map(([className, prob]) => {
                const isWinner = className.toLowerCase() === (heart.prediction || '').toLowerCase();
                const pct = (prob * 100).toFixed(2);
                return (
                  <div key={className} className="prob-row">
                    <div className={`prob-label-row ${isWinner ? 'is-winner' : ''}`}>
                      <span>{className}</span>
                      <span className="percentage">{pct}%</span>
                    </div>
                    <div className="prob-track">
                      <div
                        className={`prob-fill ${isWinner ? 'is-winner' : ''}`}
                        style={{ width: `${Math.min(100, Math.max(0, prob * 100))}%` }}
                      />
                    </div>
                  </div>
                );
              })}
          </div>

          <div className="result-footer-text">
            Real-time probability outputs generated by the trained multitask model.
          </div>
        </div>

        {/* CARD 2 — LUNG ACOUSTIC ANALYSIS */}
        <div className="result-card highlighted">
          <div className="result-header">
            <div className="result-task-title">Lung Acoustic Analysis</div>
            <span className={`result-prediction-badge ${getBadgeClass(lung_acoustic?.prediction)}`}>
              {lung_acoustic?.prediction?.toUpperCase() || '—'}
            </span>
          </div>

          <div className="prob-list">
            {lung_acoustic &&
              Object.entries(lung_acoustic.probabilities).map(([className, prob]) => {
                const isWinner = className.toLowerCase() === (lung_acoustic.prediction || '').toLowerCase();
                const pct = (prob * 100).toFixed(2);
                return (
                  <div key={className} className="prob-row">
                    <div className={`prob-label-row ${isWinner ? 'is-winner' : ''}`}>
                      <span>{className}</span>
                      <span className="percentage">{pct}%</span>
                    </div>
                    <div className="prob-track">
                      <div
                        className={`prob-fill ${isWinner ? 'is-winner' : ''}`}
                        style={{ width: `${Math.min(100, Math.max(0, prob * 100))}%` }}
                      />
                    </div>
                  </div>
                );
              })}
          </div>

          <div className="result-footer-text">
            Real-time probability outputs generated by the trained multitask model.
          </div>
        </div>

        {/* CARD 3 — LUNG DISEASE ANALYSIS */}
        <div className="result-card highlighted">
          <div className="result-header">
            <div className="result-task-title">Lung Disease Classification</div>
            <span className={`result-prediction-badge ${getBadgeClass(lung_disease?.prediction)}`}>
              {lung_disease?.prediction?.toUpperCase() || '—'}
            </span>
          </div>

          <div className="prob-list">
            {lung_disease &&
              Object.entries(lung_disease.probabilities).map(([className, prob]) => {
                const isWinner = className.toLowerCase() === (lung_disease.prediction || '').toLowerCase();
                const pct = (prob * 100).toFixed(2);
                return (
                  <div key={className} className="prob-row">
                    <div className={`prob-label-row ${isWinner ? 'is-winner' : ''}`}>
                      <span>{className}</span>
                      <span className="percentage">{pct}%</span>
                    </div>
                    <div className="prob-track">
                      <div
                        className={`prob-fill ${isWinner ? 'is-winner' : ''}`}
                        style={{ width: `${Math.min(100, Math.max(0, prob * 100))}%` }}
                      />
                    </div>
                  </div>
                );
              })}
          </div>

          <div className="result-footer-text">
            Real-time probability outputs generated by the trained multitask model.
          </div>
        </div>
      </div>

      {/* CLARITY DISTINCTION BANNER: BENCHMARK vs LIVE DEMONSTRATION */}
      <div className="demo-distinction-banner">
        <div className="distinction-item">
          <span className="distinction-tag live">LIVE DEMONSTRATION</span>
          <span className="distinction-text">
            Real-time probability outputs generated by the trained multitask model. These are predictions generated for the uploaded audio as demonstration outputs and are not themselves evidence of model accuracy or clinical diagnosis.
          </span>
        </div>
        <div className="distinction-item">
          <span className="distinction-tag benchmark">MODEL BENCHMARK RESULTS</span>
          <span className="distinction-text">
            Model performance is evaluated separately via held-out test-set evaluation.
          </span>
        </div>
      </div>
    </div>
  );
}
